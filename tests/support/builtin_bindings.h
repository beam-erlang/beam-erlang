/* Explicit test-owned unions preserve one destination for each implementation. */
static inline int beam_test_append_bindings(beam_builtin_binding *out, size_t capacity,
        size_t *count, const beam_builtin_binding *items, size_t length)
{
    for (size_t i=0;i<length;++i) {
        size_t j;
        for (j=0;j<*count;++j) if (!strcmp(out[j].implementation,items[i].implementation)) break;
        if (j<*count) {
            if (strcmp(out[j].module,items[i].module) || strcmp(out[j].function,items[i].function) ||
                out[j].arity!=items[i].arity) return 0;
        } else {
            if (*count==capacity) return 0;
            out[(*count)++]=items[i];
        }
    }
    return 1;
}

